'use strict';
// Sanitized stage diagnostics only: never expose provider exception text, URLs,
// request bodies, credentials, or dynamic symbols in unattended cron logs.
const DIRECT=new Set([
 'STAGING_CONFIGURATION_INCOMPLETE','STAGING_WORKBOOK_METADATA_UNVERIFIED',
 'PREOPEN_PREPARATION_MISSING','STAGING_WORKBOOK_OR_RUNTIME_UNAVAILABLE',
 'STAGING_LEDGER_EXCEPTION','STAGING_RESEARCH_EXCEPTION','STAGING_MODEL_EXCEPTION',
 'STAGING_SHEET_EXCEPTION','STAGING_WEBSITE_EXCEPTION','STAGING_EMAIL_EXCEPTION'
]);
const PREOPEN_CONFLICT=new Set([
 'PREOPEN_IDENTITY_MISMATCH','PREOPEN_HASH_MISMATCH',
 'PREOPEN_SESSION_INCOMPLETE','PREOPEN_TIME_INVALID'
]);
const MODEL_EVIDENCE=new Set([
 'DELAYED_REVIEW_UNVERIFIED','MISSING_HOLDING_EVIDENCE',
 'PREOPEN_EXIT_QUEUE_INCOMPLETE','INVALID_EXIT_QUEUE','INVALID_EXIT_TRIGGER'
]);
function safeStagingReason(reason){
 if(DIRECT.has(reason))return reason;
 if(reason==='OUTSIDE_MORNING_DECISION_WINDOW'||
    reason==='RESEARCH_COMPLETED_AFTER_DECISION_WINDOW')return 'STAGING_DECISION_WINDOW_EXPIRED';
 if(typeof reason!=='string')return 'STAGING_VERIFICATION_INCOMPLETE';
 if(reason.startsWith('MODEL_CYCLE:')){
  const code=reason.slice('MODEL_CYCLE:'.length);
  if(code==='EXACT_0940_BAR_REQUIRED'||code==='ENTRY_0940_QUOTE_MISSING')
   return 'STAGING_FIXED_0940_BAR_MISSING';
  if(code==='INVALID_0940_BAR'||code==='INVALID_OR_DUPLICATE_FIXED_QUOTE')
   return 'STAGING_FIXED_0940_BAR_INVALID';
  if(code.startsWith('YAHOO_MINUTE_DATA_HTTP_'))
   return 'STAGING_MINUTE_SOURCE_UNAVAILABLE';
  if(['INVALID_YAHOO_CHART','YAHOO_MINUTE_TIMESTAMP_SEQUENCE_INVALID',
      'YAHOO_MINUTE_OHLCV_LENGTH_MISMATCH'].includes(code))
   return 'STAGING_MINUTE_SOURCE_INVALID';
  if(PREOPEN_CONFLICT.has(code))return 'STAGING_PREOPEN_STATE_CONFLICT';
  if(MODEL_EVIDENCE.has(code))return 'STAGING_MODEL_EVIDENCE_INCOMPLETE';
  return 'STAGING_MODEL_CYCLE_FAILED';
 }
 if(reason.startsWith('SHEET:'))return 'STAGING_SHEET_VERIFICATION_FAILED';
 if(reason.startsWith('WEBSITE:'))return 'STAGING_WEBSITE_PARITY_FAILED';
 return 'STAGING_VERIFICATION_INCOMPLETE';
}
module.exports={safeStagingReason};
